export const RPG_LEVELS = [
    ...INITIAL_RPG_LEVEL_TITLES.map((title, index) => ({
        level: index + 1,
        title,
        xp: index === 0 ? 0 : (index + 1) * 10000,
    })),
    ...ADDITIONAL_LEVEL_TITLES.map((title, index) => ({
        level: INITIAL_RPG_LEVEL_TITLES.length + index + 1,
        title,
        xp: (INITIAL_RPG_LEVEL_TITLES.length + index + 1) * 10000,
    })),
];

export interface RpgProgress {
    level: number;
    title: string;
    progress: number;
    nextXp?: number;
}

export const getRpgProgress = (xp: number): RpgProgress => {
    const currentIndex = RPG_LEVELS.reduce(
        (index, level, candidateIndex) => (xp >= level.xp ? candidateIndex : index),
        0
    );
    const current = RPG_LEVELS[currentIndex];
    const next = RPG_LEVELS[currentIndex + 1];
    return {
        level: current.level,
        title: current.title,
        progress: next ? ((xp - current.xp) / (next.xp - current.xp)) * 100 : 100,
        nextXp: next?.xp,
    };
};
